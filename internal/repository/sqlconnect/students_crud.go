func GetStudentsHandlerFunc(r *http.Request) ([]models.Student, error) {
	var args []interface{}

	query := "Select id, first_name, last_name, email, class from students where 1=1"
	query, args = utils.AddFilters(r, query, args)

	rows, err := DB.Query(query, args...)
	if err != nil {
		return nil, err
	}
	defer rows.Close()

	studentList := make([]models.Student, 0)

	for rows.Next() {
		var student models.Student
		err := rows.Scan(&student.ID, &student.FirstName, &student.LastName, &student.Email, &student.Class)
		if err != nil {
			return studentList, err
		}
		studentList = append(studentList, student)
	}
	if err := rows.Err(); err != nil {
		return nil, err
	}

	return studentList, nil
}

func AddStudentHandlerFunc(r *http.Request) ([]models.Student, error) {
	// 1. Prepare Validation Metadata
	studentType := reflect.TypeOf(models.Student{})
	requiredFields := make(map[string]bool)

	for i := 0; i < studentType.NumField(); i++ {
		field := studentType.Field(i)
		jsonKey := strings.Split(field.Tag.Get("json"), ",")[0]
		// Exclude ID from required check (usually generated by DB)
		if jsonKey != "id" {
			requiredFields[jsonKey] = true
		}
	}

	// 2. Decode JSON with Strict Validation
	bodyBytes, err := io.ReadAll(r.Body)
	if err != nil {
		return nil, err
	}

	var newStudents []models.Student
	decode := func(data []byte, target interface{}) error {
		decoder := json.NewDecoder(bytes.NewReader(data))
		decoder.DisallowUnknownFields() // Prevent EXTRA fields
		return decoder.Decode(target)
	}

	// Try to decode as array
	if err := decode(bodyBytes, &newStudents); err != nil {
		// If array fails, try decoding as a single object
		var singleStudent models.Student
		if errSingle := decode(bodyBytes, &singleStudent); errSingle != nil {
			return nil, fmt.Errorf("client: Invalid Request Body (Extra fields or bad format): %v", errSingle)
		}
		newStudents = []models.Student{singleStudent}
	}

	// 3. Validate Required Fields (Missing/Empty Check)
	for _, student := range newStudents {
		val := reflect.ValueOf(student)
		for i := 0; i < studentType.NumField(); i++ {
			fieldVal := val.Field(i)
			jsonKey := strings.Split(studentType.Field(i).Tag.Get("json"), ",")[0]

			if requiredFields[jsonKey] && fieldVal.Kind() == reflect.String && fieldVal.String() == "" {
				return nil, fmt.Errorf("client: Required field '%s' is missing or empty", jsonKey)
			}
		}
	}

	// 4. Database Persistence
	stmt, err := DB.Prepare(utils.GenerateInsertQuery("students", models.Student{}))
	if err != nil {
		return nil, err
	}
	defer stmt.Close()

	addedStudents := make([]models.Student, len(newStudents))

	for i, newStudent := range newStudents {
		values := utils.GetStructValues(newStudent)
		res, err := stmt.Exec(values...)
		if err != nil {
			return nil, err
		}
		lastId, err := res.LastInsertId()
		if err != nil {
			return nil, err
		}
		newStudent.ID = int(lastId)
		addedStudents[i] = newStudent
	}
	return addedStudents, nil
}

func DeleteStudentsHandlerFunc(r *http.Request) error {
	var deletes []map[string]interface{}
	if err := json.NewDecoder(r.Body).Decode(&deletes); err != nil {
		return err
	}
	var deleteIdList []interface{}

	for _, v := range deletes {
		if id, ok := v["id"].(float64); ok {
			deleteIdList = append(deleteIdList, int(id))
		} else if id, ok := v["id"].(int); ok {
			deleteIdList = append(deleteIdList, id)
		} else if idStr, ok := v["id"].(string); ok {
			if id, err := strconv.Atoi(idStr); err == nil {
				deleteIdList = append(deleteIdList, id)
			}
		}
	}

	if len(deleteIdList) == 0 {
		return fmt.Errorf("no valid IDs provided")
	}
	placeholders := make([]string, len(deleteIdList))
	for i := range placeholders {
		placeholders[i] = "?"
	}
	query := fmt.Sprintf("DELETE FROM students WHERE id IN (%s)", strings.Join(placeholders, ","))
	// 3. Use DB.Exec with the list of IDs
	_, err := DB.Exec(query, deleteIdList...)
	if err != nil {
		return err
	}
	return nil
}

