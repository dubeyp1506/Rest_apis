func AddExecHandlerFunc(r *http.Request) ([]models.Exec, error) {
	// 1. Prepare Validation Metadata
	execType := reflect.TypeOf(models.Exec{})
	requiredFields := make(map[string]bool)

	for i := 0; i < execType.NumField(); i++ {
		field := execType.Field(i)
		jsonKey := strings.Split(field.Tag.Get("json"), ",")[0]
		// Exclude ID from required check (usually generated by DB)
		if jsonKey != "id" {
			requiredFields[jsonKey] = true
		}
	}

	// 2. Decode JSON with Strict Validation
	bodyBytes, err := io.ReadAll(r.Body)
	if err != nil {
		return nil, err
	}

	var newExecs []models.Exec
	decode := func(data []byte, target interface{}) error {
		decoder := json.NewDecoder(bytes.NewReader(data))
		decoder.DisallowUnknownFields() // Prevent EXTRA fields
		return decoder.Decode(target)
	}

	// Try to decode as array
	if err := decode(bodyBytes, &newExecs); err != nil {
		// If array fails, try decoding as a single object
		var singleExec models.Exec
		if errSingle := decode(bodyBytes, &singleExec); errSingle != nil {
			return nil, fmt.Errorf("client: Invalid Request Body (Extra fields or bad format): %v", errSingle)
		}
		newExecs = []models.Exec{singleExec}
	}

	// 3. Validate Required Fields (Missing/Empty Check)
	for _, exec := range newExecs {
		val := reflect.ValueOf(exec)
		for i := 0; i < execType.NumField(); i++ {
			fieldVal := val.Field(i)
			jsonKey := strings.Split(execType.Field(i).Tag.Get("json"), ",")[0]

			if requiredFields[jsonKey] && fieldVal.Kind() == reflect.String && fieldVal.String() == "" {
				return nil, fmt.Errorf("client: Required field '%s' is missing or empty", jsonKey)
			}
		}
	}

	// 4. Database Persistence
	stmt, err := DB.Prepare(utils.GenerateInsertQuery("execs", models.Exec{}))
	if err != nil {
		return nil, err
	}
	defer stmt.Close()

	addedExecs := make([]models.Exec, len(newExecs))

	for i, newExec := range newExecs {
		if newExec.Password == "" {
			return nil, utils.ErrorHandler(errors.New("Please Enter password"), "please Enter your password")
		}
		salt := make([]byte, 16)
		_, err := rand.Read(salt)
		if err != nil {
			return nil, utils.ErrorHandler(errors.New("Failed to generate salt"), "error adding data")
		}

		hash := argon2.IDKey([]byte(newExec.Password), salt, 1, 64*1024, 2, 32)
		saltBase64 := base64.StdEncoding.EncodeToString(salt)
		hashBase64 := base64.StdEncoding.EncodeToString(hash)
		encodedHash := fmt.Sprintf("%s.%s", saltBase64, hashBase64)
		newExec.Password = encodedHash

		values := utils.GetStructValues(newExec)
		res, err := stmt.Exec(values...)
		if err != nil {
			return nil, err
		}
		lastId, err := res.LastInsertId()
		if err != nil {
			return nil, err
		}
		newExec.ID = int(lastId)
		newExec.Password = "" // NEVER SEND THE PASSWORD
		addedExecs[i] = newExec
	}
	return addedExecs, nil
}

func DeleteExecsHandlerFunc(r *http.Request) error {
	var deletes []map[string]interface{}
	if err := json.NewDecoder(r.Body).Decode(&deletes); err != nil {
		return err
	}
	var deleteIdList []interface{}

	for _, v := range deletes {
		if id, ok := v["id"].(float64); ok {
			deleteIdList = append(deleteIdList, int(id))
		} else if id, ok := v["id"].(int); ok {
			deleteIdList = append(deleteIdList, id)
		} else if idStr, ok := v["id"].(string); ok {
			if id, err := strconv.Atoi(idStr); err == nil {
				deleteIdList = append(deleteIdList, id)
			}
		}
	}

	if len(deleteIdList) == 0 {
		return fmt.Errorf("no valid IDs provided")
	}
	placeholders := make([]string, len(deleteIdList))
	for i := range placeholders {
		placeholders[i] = "?"
	}
	query := fmt.Sprintf("DELETE FROM execs WHERE id IN (%s)", strings.Join(placeholders, ","))
	// 3. Use DB.Exec with the list of IDs
	_, err := DB.Exec(query, deleteIdList...)
	if err != nil {
		return err
	}
	return nil
}

