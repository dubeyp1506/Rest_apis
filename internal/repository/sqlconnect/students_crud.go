func PatchStudentsHandlerFunc(r *http.Request) error {
	var updates []map[string]interface{}

	err := json.NewDecoder(r.Body).Decode(&updates)
	if err != nil {
		return fmt.Errorf("client: invalid JSON body: %v", err)
	}

	tx, err := DB.Begin()
	if err != nil {
		return err
	}
	for _, update := range updates {
		// Robust ID extraction: handles Numbers (float64), Integers, and Strings from JSON
		var id int
		var idValid bool
		if v, ok := update["id"].(float64); ok {
			id = int(v)
			idValid = true
		} else if v, ok := update["id"].(int); ok {
			id = v
			idValid = true
		} else if v, ok := update["id"].(string); ok {
			if parsedId, err := strconv.Atoi(v); err == nil {
				id = parsedId
				idValid = true
			}
		}

		if !idValid {
			tx.Rollback()
			return fmt.Errorf("client: Invalid or missing student id in update")
		}

		var studentFromDb models.Student
		// Use tx instead of DB to keep it in the transaction
		err = tx.QueryRow("Select id, first_name, last_name, email, class from students where id = ?", id).Scan(
			&studentFromDb.ID, &studentFromDb.FirstName, &studentFromDb.LastName, &studentFromDb.Email, &studentFromDb.Class,
		)
		if err != nil {
			tx.Rollback()
			if err == sql.ErrNoRows {
				return err
			}
			return err
		}

		val := reflect.ValueOf(&studentFromDb).Elem()
		typeOf := val.Type()

		for k, v := range update {
			if k == "id" {
				continue
			}
			for i := 0; i < val.NumField(); i++ {
				filed := typeOf.Field(i)
				tag := filed.Tag.Get("json")
				jsonKey := strings.Split(tag, ",")[0]

				if jsonKey == k {
					fieldVal := val.Field(i)
					if fieldVal.CanSet() {
						currVal := reflect.ValueOf(v)
						// Fix: check if the VALUE (currVal) is convertible to the FIELD
						if currVal.Type().ConvertibleTo(fieldVal.Type()) {
							fieldVal.Set(currVal.Convert(fieldVal.Type()))
						} else {
							tx.Rollback()
							return fmt.Errorf("client: Type mismatch for field %s", k)
						}
					}
				}

			}
		}
		_, err = tx.Exec("Update students set first_name = ?, last_name = ?, email = ?, class = ? where id = ?",
			studentFromDb.FirstName, studentFromDb.LastName, studentFromDb.Email, studentFromDb.Class, studentFromDb.ID)
		if err != nil {
			tx.Rollback()
			return err
		}
	}
	if err := tx.Commit(); err != nil {
		return err
	}
	return nil
}

